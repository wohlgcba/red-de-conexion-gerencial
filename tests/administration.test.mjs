  await db.exec('reset role')
  await addOrganizationEvidence(db,key(5),'Gerente Operativo de Prueba')
  await db.query('insert into red_conexion_gerencial.admin_users(user_id,email) values($1,$2)',[id(6),'person6@example.test'])

  assert(editedHistory.some(e=>e.after.ministry==='Organismo actualizado'))
  // Public intake: verified owner only; ignores client email/identity impersonation.
  await actor(7)
  const publicRequest=await rpc('submit_access_request',['Ingreso','Nuevo','Gerente Operativo','Organismo de prueba',key(7),'Solicitud de incorporación verificada por correo'])
  assert.equal(await rpc('submit_access_request',['Ingreso','Nuevo','Gerente Operativo','Organismo de prueba',key(7),'Reintento de solicitud de incorporación']),publicRequest)

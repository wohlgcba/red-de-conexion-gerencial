  await actor(1)
  const r2=await register(2), r3=await register(3), r4=await register(4), r5=await register(5)
  assert.equal((await rpc('get_my_notifications')).unreadCount,4)
  assert.equal((await detail(r2)).validation.evidence,'pending','partial Organigrama never proves absence')
  await assert.rejects(()=>decide(r2,1,'approve'),/excepción/)
  await assert.rejects(()=>decide(r2,1,'exception','corto'),/justificación/)
  await assert.rejects(()=>decide(r2,1,'exception',null),/justificación/)
  await assert.rejects(()=>decide(r2,1,null),/inválida/)
  await actor(2)
  assert.equal((await rpc('get_my_directory_requests')).length,1)
  assert(!JSON.stringify(await rpc('get_my_directory_requests')).includes(key(2)))
  assert.equal((await rpc('get_my_notifications')).unreadCount,0)
  await assert.rejects(()=>db.query('select * from rcg_private.admin_notifications'))
  assert.equal(await rpc('get_my_directory_gate'),'pending')
  assert.equal(await rpc('is_member'),false)
  assert.deepEqual((await db.query('select id from red_conexion_gerencial.people')).rows,[])
  await assert.rejects(()=>rpc('admin_list_requests'),/denegado/)
  await assert.rejects(()=>detail(r2),/denegado/)
  await assert.rejects(()=>rpc('admin_member_identity',[id(9)]),/denegado/)
  await assert.rejects(()=>db.query('select * from rcg_private.admin_requests'))
  await assert.rejects(()=>db.query('select * from rcg_private.admin_audit'))
  await actor(1)
  let list=await rpc('admin_list_requests',['all',{}]); assert.equal(list.counts.all,4); assert.equal(list.rows.length,4)
  assert(!JSON.stringify(list.rows).includes(key(2)),'list DTO must not include identifiers')
  assert.equal((await detail(r2)).identifier,key(2))
  await db.exec('reset role')
  assert.equal((await db.query("select to_regclass('rcg_private.admin_dotacion_rows') as rows,to_regclass('rcg_private.admin_dotacion_sources') as sources")).rows[0].rows,null)
  for(const [n,role] of [[2,'Gerente Operativo de Prueba'],[3,'Analista'],[5,'Subgerente Operativo de Prueba']]) await addOrganizationEvidence(db,key(n),role)
  await actor(1)
  assert.equal((await detail(r2)).validation.ordinary,true)
  assert.equal((await detail(r3)).validation.eligibility,'other')
  assert.equal((await detail(r4)).validation.evidence,'pending')
  await decide(r2,1,'approve')
  await assert.rejects(()=>decide(r2,1,'approve'),/cambió/,'stale administrator cannot approve twice')
  await assert.rejects(()=>decide(r2,2,'approve'),/resuelta/)
  await decide(r3,1,'exception','Funciones estratégicas verificadas','non_manager')
  assert.equal((await detail(r3)).exceptionActive,true)
  const p3=(await detail(r3)).personId
  await decide(r3,2,'revoke','Revocación manual documentada')
  assert.equal((await detail(r3)).exceptionActive,false)
  await actor(3); assert.equal(await rpc('is_member'),true,'revoking an exception must not suspend access')
  await actor(1); await decide(r4,1,'reject')
  await actor(4); assert.equal(await rpc('get_my_directory_gate'),'rejected');assert.equal(await rpc('is_member'),false)
  await actor(2); assert.equal(await rpc('is_member'),true)
  assert.equal((await rpc('get_my_notifications')).unreadCount,1)
  await rpc('read_my_notifications',[null]);assert.equal((await rpc('get_my_notifications')).unreadCount,0)
  await assert.rejects(()=>rpc('submit_access_request',['Persona','Duplicada','Gerente','Prueba',key(2),'Intento duplicado de ingreso']),/ya tiene/)
  const change=await rpc('submit_profile_change',['position_title','Gerente Operativo de Nuevo Equipo','Reorganización institucional de prueba'])
  await assert.rejects(()=>rpc('submit_profile_change',['phone','123','Intento inválido de cambiar campo']),/campo/)

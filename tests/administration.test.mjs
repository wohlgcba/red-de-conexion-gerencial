  await decide(change,1,'exception','Reestructuración confirmada por organismo','discrepancy')
  await assert.rejects(()=>decide(change,1,'approve'),/cambió/,'an approved change cannot be applied twice')
  const p2=(await detail(r2)).personId
  await db.exec('reset role'); assert.equal((await db.query('select position_title from red_conexion_gerencial.people where id=$1',[p2])).rows[0].position_title,'Gerente Operativo de Nuevo Equipo')
  assert.equal((await db.query('select encrypted_password from auth.users where id=$1',[id(2)])).rows[0].encrypted_password,'unchanged')
  await actor(2)
  const stale=await rpc('submit_profile_change',['ministry','Otro organismo','Cambio informado por integrante'])
  await actor(1); await rpc('admin_manage_member',[p2,2,'deactivate','Suspensión manual de prueba'])
  await assert.rejects(()=>decide(stale,1,'exception','Decisión con datos desactualizados','other'),/perfil cambió/)
  await actor(2); assert.equal(await rpc('is_member'),false)
  assert.deepEqual((await db.query('select id from red_conexion_gerencial.people')).rows,[])
  await assert.rejects(()=>rpc('get_organization_chart'),/autorizado/)
  await actor(1); await rpc('admin_manage_member',[p2,3,'activate','Reactivación manual de prueba'])
  let members=await rpc('admin_list_members',[{pageSize:1,page:1}]);assert.equal(members.rows.length,1);assert.equal(members.total,2)
  assert(!JSON.stringify(members.rows).includes(key(3)))
  assert(members.rows.some(p=>p.validation.reasons.includes('role_changed')||p.validation.reasons.includes('non_manager')))
  // Two records differing only in email case/whitespace are surfaced, never merged automatically.
  await db.exec('reset role')
  await db.query("insert into red_conexion_gerencial.people(given_name,family_name,position_title,ministry,email,phone,source_row) values('Otra','Identidad','Analista','Prueba',$1,'',null)",['PERSON5@example.test'])
  await actor(1)
  d=await detail(r5); assert.equal(d.validation.duplicateEmail,1)
  await assert.rejects(()=>decide(r5,1,'exception','No se permite saltar identidad','duplicate_email'),/conflicto de identidad/)
  const before=(await rpc('admin_list_requests',['all',{}])).counts
  assert.equal(before.all,before.access+before.change,'overlapping exceptions are not added to total')
  assert.equal((await rpc('admin_list_requests',['all',{query:'persona ejemplo 5'}])).total,1)
  assert.equal((await rpc('admin_list_requests',['all',{query:key(5)}])).total,1)
